"""Offline checks for docs/firearm-coverage.json (issue #4443 phase 0).

The manifest is generated by run.py from compiler-resolved defaults. These
checks need no BYOND: the stored rows must still classify the same way, and
every gun type declared in source must appear in the manifest, so a new gun
cannot skip classification.
"""
import json
from pathlib import Path
import re
import sys
import unittest

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
import firearm_coverage  # noqa: E402

HEADER = re.compile(r'^(/obj/item/weapon/gun(?:/[A-Za-z_][A-Za-z_0-9]*)*)\s*(?://.*)?$')


def declared_gun_types():
    found = {}
    for path in sorted((ROOT / 'code').rglob('*.dm')):
        depth = 0
        for number, line in enumerate(path.read_text(encoding='utf-8-sig', errors='replace').splitlines(), 1):
            # Skip block comments at top level; gun headers never sit inside one.
            depth += line.count('/*') - line.count('*/')
            if depth > 0:
                continue
            match = HEADER.match(line)
            if match:
                found.setdefault(match[1], f'{path.relative_to(ROOT).as_posix()}:{number}')
    return found


class CoverageManifestTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.manifest = json.loads((ROOT / firearm_coverage.MANIFEST).read_text(encoding='utf-8'))
        cls.types = {e['path']: e for e in cls.manifest['types']}

    def test_schema_and_summary(self):
        self.assertEqual(self.manifest['schema_version'], firearm_coverage.SCHEMA_VERSION)
        summary = self.manifest['summary']
        self.assertEqual(summary['types'], len(self.types))
        self.assertEqual(summary['modern'], sum(e['scope'] == 'modern' for e in self.types.values()))
        self.assertEqual(sum(summary['by_category'].values()), len(self.types))

    def test_stored_rows_classify_the_same_way(self):
        rebuilt = firearm_coverage.build([
            {'path': e['path'], 'name': e['name'], 'caliber': e['caliber'],
             'load_method': e['load_method'], 'max_shells': e['max_shells'],
             'magazine_type': e['magazine_type'], 'ammo_type': e['ammo_type'],
             'is_laser_mg': e['category'] == 'energy' and e['caliber'] not in firearm_coverage.CALIBER_CATEGORY}
            for e in self.types.values()])
        for entry in rebuilt['types']:
            self.assertEqual(entry['category'], self.types[entry['path']]['category'], entry['path'])

    def test_no_unclassified_types(self):
        unclassified = sorted(p for p, e in self.types.items() if e['category'] == 'unclassified')
        self.assertEqual(unclassified, [], 'add a rule in tests/firearm_coverage/firearm_coverage.py')

    def test_modern_scope_has_cartridge_calibers_only(self):
        for path, entry in self.types.items():
            if entry['scope'] == 'modern' and 'review' not in entry:
                self.assertNotIn(entry['caliber'], ('laser', 'laserb', 'taser', 'rocket', 'stoneball'), path)

    def test_every_declared_gun_type_is_in_the_manifest(self):
        missing = {p: loc for p, loc in declared_gun_types().items() if p not in self.types}
        self.assertEqual(missing, {}, 'new gun types need the manifest regenerated: '
                         'python3 tests/firearm_coverage/run.py --byond-bin <BYOND bin> --write')

    def test_category_rules(self):
        cases = {
            '/obj/item/weapon/gun/projectile/automatic/stationary/pkm': 'machine_gun_mounted',
            '/obj/item/weapon/gun/projectile/automatic/laser/x': 'energy',
            '/obj/item/weapon/gun/projectile/ancient/arquebus': 'blackpowder',
            '/obj/item/weapon/gun/projectile/flintlock/musket': 'blackpowder',
            '/obj/item/weapon/gun/launcher/rocket': 'launcher',
            '/obj/item/weapon/gun/projectile/submachinegun/ak47': 'submachine_gun',
            '/obj/item/weapon/gun/projectile/nonsense': 'unclassified',
        }
        for path, expected in cases.items():
            self.assertEqual(firearm_coverage.category(path, {'caliber': 'a762x39'}), expected, path)
        self.assertEqual(firearm_coverage.category('/obj/item/weapon/gun/projectile/pistol/x', {'caliber': 'laser'}), 'energy')
        self.assertEqual(firearm_coverage.category('/obj/item/weapon/gun/projectile/automatic/stationary/atgm',
                                                   {'caliber': 'rocket'}), 'launcher')


if __name__ == '__main__':
    unittest.main()
