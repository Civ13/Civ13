"""Render the opt-in Indian Ocean reef fixture, not an admitted region map."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "tests/ocean_maps/indian_reef_shelf.dmm"
SIZE = (40, 30)
REEF = (26, 15)
BUOY = (26, 8)
AREA = "/area/caribbean/nomads/ocean"
SALTWATER = "/turf/floor/beach/water/deep/saltwater"
SHELF = SALTWATER + "/underwater/sea_layer"


def site(dx, dy):
    # An irregular ring of shelf water surrounding exposed bedrock ridges.
    # Work in integers; the same site comes out of every generation.
    outer = 49 * dx * dx + 100 * dy * dy <= 4900
    inner = 16 * (dx + 1) ** 2 + 36 * dy * dy <= 576
    # Two cuts break the inner ridge so it reads as a reef, not a pool.
    return outer and (not inner or abs(dy) <= 1)


def levels():
    w, h = SIZE
    rx, ry = REEF
    surface = [["a"] * w for _ in range(h)]
    shelf = [["e"] * w for _ in range(h)]
    surface[0][0] = "b"
    for y in range(12, 19):
        for x in range(3, 10):
            if abs(x - 6) + abs(y - 15) <= 4:
                surface[y - 1][x - 1] = "c"
    surface[14][5] = "d"
    bx, by = BUOY
    surface[by - 1][bx - 1] = "f"
    for y in range(1, h + 1):
        for x in range(1, w + 1):
            if site(x - rx, y - ry) and surface[y - 1][x - 1] in ("a", "f"):
                shelf[y - 1][x - 1] = "g"
    return surface, shelf


def render():
    keys = {
        "a": (SALTWATER, AREA),
        "b": (
            "/obj/map_metadata/nomads/ocean/indian{underground_compiled_z = 2; underground_depth = 1}",
            SALTWATER, AREA,
        ),
        "c": ("/turf/floor/beach/sand", AREA),
        "d": ('/obj/effect/landmark{icon_state = "x3"; name = "JoinLateCiv"}', "/turf/floor/beach/sand", AREA),
        "e": ("/turf/wall/rockwall/bedrock", AREA),
        "f": (
            '/obj/structure/buoy/yellow{anchored = 1; icon_state = "buoy_y1"; message = "Indian Ocean reef; dive within the shelf, north of this marker."}',
            SALTWATER, AREA,
        ),
        "g": (SHELF, AREA),
    }
    header = "\n".join(f'"{k}" = ({",".join(v)})' for k, v in keys.items())
    blocks = []
    for z, grid in enumerate(levels(), 1):
        rows = "\n".join("".join(row) for row in reversed(grid))
        blocks.append(f'(1,1,{z}) = {{"\n{rows}\n"}}')
    return "\n\n".join([
        "// Non-admitted test fixture; generated by python3 tools/ocean_maps/reef_fixture.py.\n" + header,
        *blocks,
    ]) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    result = render()
    if args.check:
        return int(not FIXTURE.is_file() or FIXTURE.read_text(encoding="utf-8") != result)
    FIXTURE.write_text(result, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
